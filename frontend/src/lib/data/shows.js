export function getUpcomingShows() {
  const today = new Date().toISOString().split('T')[0];
  return shows.filter((s) => s.date > today);
}

export function getRecentShows(limit = 5) {
  return [...shows].sort((a, b) => new Date(b.date) - new Date(a.date)).slice(0, limit);
}

export function getShowsByArtist(artistId) {
  return shows.filter((s) => s.artistId === artistId);
}
