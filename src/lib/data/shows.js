export function getShowById(id) {
  return shows.find((s) => s.id === Number(id));
}

export function getUpcomingShows() {
  const today = new Date().toISOString().split('T')[0];
  return shows
    .filter((s) => !s.attended && s.date > today)
    .sort((a, b) => new Date(a.date) - new Date(b.date));
}

export function getRecentShows(limit = 5) {
  return [...shows]
    .filter((s) => s.attended)
    .sort((a, b) => new Date(b.date) - new Date(a.date))
    .slice(0, limit);
}

export function getShowsByVenue(venueName) {
  return shows.filter((s) => s.venue === venueName);
}

export function getShowsByArtist(artistId) {
  return shows.filter((s) => s.artistId === artistId);
}
